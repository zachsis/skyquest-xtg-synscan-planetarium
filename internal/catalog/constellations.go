// StarsByConstellation returns a map of constellation abbreviation to the
// unique HIP IDs that appear in its stick figure.
func StarsByConstellation(
	lines []ConstellationLine,
) map[string][]int {
	seen := make(map[string]map[int]struct{})
	for _, l := range lines {
		if seen[l.Constellation] == nil {
			seen[l.Constellation] = make(map[int]struct{})
		}
		seen[l.Constellation][l.Hip1] = struct{}{}
		seen[l.Constellation][l.Hip2] = struct{}{}
	}
	result := make(map[string][]int, len(seen))
	for con, ids := range seen {
		slice := make([]int, 0, len(ids))
		for id := range ids {
			slice = append(slice, id)
		}
		result[con] = slice
	}
	return result
}
